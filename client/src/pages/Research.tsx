import React, { useState } from 'react';
import { useNavigate } from 'react-router-dom';
import {
  Search,
  ExternalLink,
  Download,
  FileSpreadsheet,
  FileText,
  Loader2,
  Sparkles,
  Bot,
  Building2,
  Globe2,
  ArrowRight
} from 'lucide-react';
import { jsPDF } from 'jspdf';
import { api } from '../services/api';
import { ResearchResult } from '../types';
import ReactMarkdown from 'react-markdown';
import remarkGfm from 'remark-gfm';

export const Research: React.FC = () => {
  const navigate = useNavigate();
  const [topic, setTopic] = useState('');
  const [industry, setIndustry] = useState('');
  const [targetRegion, setTargetRegion] = useState('India');
  const [isLoading, setIsLoading] = useState(false);
  const [result, setResult] = useState<ResearchResult | null>(null);
  const [error, setError] = useState<string | null>(null);

  const handleResearch = async (e: React.FormEvent) => {
    e.preventDefault();
    if (!topic.trim()) return;

    setIsLoading(true);
    setError(null);
    setResult(null);

    try {
      const data = await api.conductResearch(topic.trim(), industry, targetRegion);
      setResult(data);
    } catch (err: any) {
      setError(err.message || 'Research failed.');
    } finally {
      setIsLoading(false);
    }
  };

  const exportAsPdf = () => {
    if (!result) return;
    const doc = new jsPDF();
    doc.setFont('helvetica', 'bold');
    doc.setFontSize(16);
    doc.text(`Market Research: ${result.topic}`, 14, 20);

    doc.setFont('helvetica', 'normal');
    doc.setFontSize(10);
    doc.text(`Generated by MarketMate AI on ${new Date().toLocaleDateString()}`, 14, 28);

    const content = result.report || result.summary || '';
    const splitText = doc.splitTextToSize(content, 180);
    let y = 38;
    for (const line of splitText) {
      if (y > 280) {
        doc.addPage();
        y = 20;
      }
      doc.text(line, 14, y);
      y += 5;
    }

    // Add sources
    if (result.sources && result.sources.length > 0) {
      if (y > 260) {
        doc.addPage();
        y = 20;
      }
      y += 6;
      doc.setFont('helvetica', 'bold');
      doc.text('Sources & Citations:', 14, y);
      y += 6;
      doc.setFont('helvetica', 'normal');
      result.sources.forEach((s) => {
        if (y > 280) {
          doc.addPage();
          y = 20;
        }
        doc.text(`- ${s.title}: ${s.url}`, 14, y);
        y += 5;
      });
    }

    doc.save(`MarketMate_Research_${result.topic.replace(/\s+/g, '_')}.pdf`);
  };

  const exportAsCsv = () => {
    if (!result) return;
    const reportContent = result.report || result.summary || '';
    const rows = [
      ['Topic', result.topic],
      ['Generated At', new Date().toISOString()],
      ['Report Content', `"${reportContent.replace(/"/g, '""')}"`]
    ];

    if (result.sources) {
      rows.push(['Sources', '']);
      result.sources.forEach(s => rows.push([s.title, s.url]));
    }

    const csvContent = 'data:text/csv;charset=utf-8,' + rows.map(e => e.join(',')).join('\n');
    const encodedUri = encodeURI(csvContent);
    const link = document.createElement('a');
    link.setAttribute('href', encodedUri);
    link.setAttribute('download', `MarketMate_Research_${result.topic.replace(/\s+/g, '_')}.csv`);
    document.body.appendChild(link);
    link.click();
    document.body.removeChild(link);
  };

  return (
    <div className="max-w-5xl mx-auto py-8 px-6 space-y-6">
      {/* Header */}
      <div>
        <div className="flex items-center gap-2">
          <div className="w-8 h-8 rounded-lg bg-violet-100 text-violet-700 flex items-center justify-center">
            <Search className="w-4 h-4" />
          </div>
          <div>
            <h1 className="text-xl font-bold text-slate-900 tracking-tight">Web Research Agent</h1>
            <p className="text-xs text-slate-500">
              Live Google Search grounded intelligence on companies, competitors, ICPs, and market positioning.
            </p>
          </div>
        </div>
      </div>

      {/* Research Form */}
      <div className="bg-white rounded-2xl border border-slate-200/90 p-6 shadow-sm">
        <form onSubmit={handleResearch} className="space-y-4">
          <div className="grid grid-cols-1 sm:grid-cols-4 gap-3">
            <div className="sm:col-span-2">
              <label className="block text-xs font-semibold text-slate-700 mb-1">
                Company or Market Research Topic
              </label>
              <input
                type="text"
                value={topic}
                onChange={(e) => setTopic(e.target.value)}
                placeholder="e.g. Eye Hospital Sector, EV Charging Infrastructure, Fintech"
                required
                className="w-full bg-slate-50 border border-slate-200 rounded-lg px-3 py-2 text-xs text-slate-800 placeholder-slate-400 focus:outline-hidden focus:border-violet-500"
              />
            </div>

            <div>
              <label className="block text-xs font-semibold text-slate-700 mb-1">
                Industry / Sector (Optional)
              </label>
              <input
                type="text"
                value={industry}
                onChange={(e) => setIndustry(e.target.value)}
                placeholder="e.g. Healthcare, Automotive"
                className="w-full bg-slate-50 border border-slate-200 rounded-lg px-3 py-2 text-xs text-slate-800 placeholder-slate-400 focus:outline-hidden focus:border-violet-500"
              />
            </div>

            <div>
              <label className="block text-xs font-semibold text-slate-700 mb-1">
                Target Region
              </label>
              <select
                value={targetRegion}
                onChange={(e) => setTargetRegion(e.target.value)}
                className="w-full bg-slate-50 border border-slate-200 rounded-lg px-3 py-2 text-xs text-slate-800 focus:outline-hidden focus:border-violet-500"
              >
                <option value="India">India</option>
                <option value="United States">United States</option>
                <option value="Europe / UK">Europe / UK</option>
                <option value="Southeast Asia">Southeast Asia</option>
                <option value="Global">Global</option>
              </select>
            </div>
          </div>

          <div className="flex items-center justify-between pt-2">
            <div className="flex items-center gap-2 text-[11px] text-slate-500">
              <Sparkles className="w-3.5 h-3.5 text-violet-600" />
              <span>Grounded with Google Search • Citations verified</span>
            </div>

            <button
              type="submit"
              disabled={isLoading || !topic.trim()}
              className="flex items-center gap-1.5 px-4 py-2 rounded-lg bg-violet-600 hover:bg-violet-700 text-white text-xs font-semibold shadow-sm transition disabled:opacity-40"
            >
              {isLoading ? (
                <>
                  <Loader2 className="w-3.5 h-3.5 animate-spin" />
                  <span>Researching Web...</span>
                </>
              ) : (
                <>
                  <Search className="w-3.5 h-3.5" />
                  <span>Start Research</span>
                </>
              )}
            </button>
          </div>
        </form>
      </div>

      {error && (
        <div className="p-4 rounded-xl bg-red-50 border border-red-200 text-red-700 text-xs">
          {error}
        </div>
      )}

      {/* Research Results */}
      {result && (
        <div className="bg-white rounded-2xl border border-slate-200/90 p-6 shadow-sm space-y-6">
          <div className="flex flex-col sm:flex-row sm:items-center justify-between gap-3 pb-4 border-b border-slate-100">
            <div>
              <span className="text-[10px] uppercase font-bold px-2 py-0.5 rounded bg-violet-100 text-violet-800 tracking-wider">
                Research Report
              </span>
              <h2 className="text-base font-bold text-slate-900 mt-1">{result.topic}</h2>
            </div>

            <div className="flex items-center gap-2">
              <button
                onClick={exportAsPdf}
                className="flex items-center gap-1.5 px-3 py-1.5 rounded-lg border border-slate-200 hover:bg-slate-50 text-slate-700 text-xs font-medium transition"
              >
                <Download className="w-3.5 h-3.5 text-slate-500" />
                <span>Export PDF</span>
              </button>
              <button
                onClick={exportAsCsv}
                className="flex items-center gap-1.5 px-3 py-1.5 rounded-lg border border-slate-200 hover:bg-slate-50 text-slate-700 text-xs font-medium transition"
              >
                <FileSpreadsheet className="w-3.5 h-3.5 text-slate-500" />
                <span>Export CSV</span>
              </button>
              <button
                onClick={() =>
                  navigate(`/workspace?prompt=${encodeURIComponent(`Let's discuss this research report on ${result.topic}:\n\n${(result.report || result.summary || '').substring(0, 500)}...`)}`)
                }
                className="flex items-center gap-1 px-3 py-1.5 rounded-lg bg-violet-600 hover:bg-violet-700 text-white text-xs font-semibold transition shadow-sm"
              >
                <Bot className="w-3.5 h-3.5" />
                <span>Discuss in Chat</span>
              </button>
            </div>
          </div>

          {/* Sources Carousel / List */}
          {result.sources && result.sources.length > 0 && (
            <div className="p-4 rounded-xl bg-slate-50 border border-slate-200/80">
              <h3 className="text-xs font-bold text-slate-800 uppercase tracking-wider mb-2.5 flex items-center gap-1.5">
                <Globe2 className="w-3.5 h-3.5 text-violet-600" />
                Verified Web Sources ({result.sources.length})
              </h3>
              <div className="grid grid-cols-1 sm:grid-cols-2 md:grid-cols-3 gap-2">
                {result.sources.map((s, idx) => (
                  <a
                    key={idx}
                    href={s.url}
                    target="_blank"
                    rel="noreferrer"
                    className="p-2.5 rounded-lg bg-white border border-slate-200/70 hover:border-violet-300 hover:shadow-sm transition flex items-center justify-between text-xs group"
                  >
                    <span className="font-medium text-slate-700 truncate pr-2 group-hover:text-violet-700">
                      {s.title}
                    </span>
                    <ExternalLink className="w-3 h-3 text-slate-400 group-hover:text-violet-600 shrink-0" />
                  </a>
                ))}
              </div>
            </div>
          )}

          {/* Markdown Report Body */}
          <div className="prose prose-xs max-w-none text-slate-800 leading-relaxed">
            <ReactMarkdown remarkPlugins={[remarkGfm]}>
              {result.report || result.summary}
            </ReactMarkdown>
          </div>
        </div>
      )}
    </div>
  );
};
